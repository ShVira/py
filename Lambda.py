# Функціональні вирази (лямбда)
# У програмуванні розрізняють:
# вирази (expressions) та інструкції (statements).
# І те, і інше — синтаксично коректні декларації
# мовою програмування. Інструкції — такі, що не
# мають результату, вирази — такі, що мають.
# Результати виразів можуть зберігатись у змінних
# або бути частиною інших виразів чи інструкцій.
# Найбільш поширений приклад:
# умовна інструкція (if cond: action)
# умовний вираз (x = 10 if cond else 20)
# В сучасних традиціях програмування — утворення
# двох варіантів більшості інструментів у формах
# виразів та інструкцій: switch-expression / switch statement, ...
# functional statement / functional expression

x = 10


def init_lam2():
    global lam2
    lam2 = lambda: print(f"Lambda 2: x = {x}")


def init_lam3():
    global lam3
    x = 20
    lam3 = lambda: print(f"Lambda 3: x = {x}")


def iife_demo():
    lam1 = lambda: print('Lambda 1')
    lam1()

    # Одна з можливостей функціональних виразів — одноразове
    # використання об'єктів (після якого вони передаються GC)
    # IIFE (Immediately Invoked Function Expression)
    (lambda: print('Lambda IIFE'))()

    # IIFE покращують безпеку коду - можливість повторного
    # виклику нівелюється (через знищення об'єкту, що викликається)

    # Capture (closure) - захоп локальної області
    # Класичний приклад - утворення переліку функцій за
    # допомогою циклу - функцій, що виводять свій номер (індекс)
    funcs = []
    for i in range(5):
        funcs.append(lambda: print(f"My index is {i}"))

    funcs[2]()  # My index is 4
    funcs[0]()  # My index is 4

    # Чому всі функції виводять однаковий результат (4)?
    # Python є інтерпретатором і формує тіло функції без
    # компіляції — просто текст: print(f"My index is {i}")
    # ! без підстановки "i" до рядка.
    # Підстановка відбувається у момент виконання функції,
    # коли вона викликається, а на момент виклику цикл
    # завершено та "i" має значення останньої ітерації (4)
    # [у JS було б 5 через іншу організацію роботи циклів]
    # Така робота називається "пізнім зв'язуванням"
    # [підстановка на етапі компіляції (декларації) - раннє зв'язування]
    # --------
    print("---------")
    funcs_2 = [
        # результатом IIFE
        (lambda x: lambda: print(f"My index is {x}"))(j)
        for j in range(5)
    ]
    funcs_2[2]()


def main():
    # iife_demo()
    init_lam2()
    lam2()  # Lambda 2: x = 10
    init_lam3()
    lam3()  # Lambda 3: x = 20 -- перевага надається локальній змінній + захоп


if __name__ == '__main__':
    main()